import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const dir = await mkdtemp(join(tmpdir(), 'actscope-smoke-'));
try {
  const page = await browser.newPage({ viewport: { width: 1512, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.ACTSCOPE_URL || 'http://127.0.0.1:5173/#explorer');
  await page.getByRole('heading', { name: 'ActScope', exact: true }).waitFor();
  assert.match(await page.locator('.metrics').innerText(), /320.00 MiB/);
  await page.locator('summary').click();
  const editor = page.getByRole('textbox', { name: '激活属性 JSON' });
  const value = JSON.parse(await editor.inputValue());
  value.savedBy = [];
  await editor.fill(JSON.stringify(value));
  await page.getByRole('button', { name: '校验并应用' }).click();
  await page.waitForFunction(() => document.querySelector('.metrics').textContent.includes('304.00 MiB'));
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.metrics')?.textContent.includes('304.00 MiB'));
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 JSON' }).click();
  const file = join(dir, 'graph.json');
  await (await download).saveAs(file);
  const saved = JSON.parse(await readFile(file, 'utf8'));
  assert.deepEqual(saved.tensors.find(t => t.id === 'normed').savedBy, []);
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":99}') });
  await page.getByRole('status').filter({ hasText: '导入失败' }).waitFor();
  assert.match(await page.locator('.metrics').innerText(), /304.00 MiB/);
  await page.locator('input[type=file]').setInputFiles('public/examples/qwen3-layer.json');
  await page.waitForFunction(() => document.querySelector('.metrics').textContent.includes('320.00 MiB'));
  await page.getByRole('button', { name: 'Attention', exact: true }).click();
  assert.equal(await page.locator('.react-flow__node').filter({ hasText: 'Grouped Expert FC1' }).count(), 0);
  await page.getByRole('checkbox', { name: '保存依赖' }).uncheck();
  assert.equal(await page.locator('.graph-node.backward').count(), 0);
  await page.getByRole('checkbox', { name: '保存依赖' }).check();
  await page.getByRole('button', { name: '整层', exact: true }).click();
  await page.locator('[data-id="v"]').click();
  assert.match(await page.locator('aside').innerText(), /qkv_out, v/);
  await page.screenshot({ path: '/tmp/actscope-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: '实测小模型', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.metrics')?.textContent.includes('48'));
  assert.match(await page.locator('aside').innerText(), /512.00 KiB/);
  assert.match(await page.locator('aside').innerText(), /2.00 KiB/);
  assert.match(await page.locator('aside').innerText(), /\[1, 0\]/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1512, height: 1050 });
  await page.screenshot({ path: '/tmp/actscope-observed.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Browser smoke passed: rendering, edit/reload, import/export, validation, module filter, saved edges, shared storage, mobile width.');
} finally { await browser.close(); await rm(dir, { recursive: true, force: true }); }
